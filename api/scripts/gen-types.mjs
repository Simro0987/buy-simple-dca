#!/usr/bin/env node
// Generates src/lib/api/types.ts from OUR Postgres (public schema), replacing the old
// Supabase-generated types. Usage:
//   DATABASE_URL=postgres://user:pass@localhost:5432/app node api/scripts/gen-types.mjs
import fs from 'node:fs';
import path from 'node:path';
import pg from 'pg';

const url = process.env.DATABASE_URL;
if (!url) {
  console.error('DATABASE_URL is required');
  process.exit(1);
}
const out = path.resolve(process.argv[2] ?? 'src/lib/api/types.ts');

const TS = {
  uuid: 'string', text: 'string', 'character varying': 'string', character: 'string', citext: 'string',
  date: 'string', 'timestamp with time zone': 'string', 'timestamp without time zone': 'string',
  'time without time zone': 'string', interval: 'string', inet: 'string', bytea: 'string',
  integer: 'number', smallint: 'number', bigint: 'number', numeric: 'number', real: 'number',
  'double precision': 'number', boolean: 'boolean', json: 'Json', jsonb: 'Json',
};

const client = new pg.Client({ connectionString: url });
await client.connect();
const { rows } = await client.query(`
  select c.table_name, c.column_name, c.data_type, c.udt_name, c.is_nullable, c.column_default,
         c.is_identity, t.table_type
    from information_schema.columns c
    join information_schema.tables t on t.table_schema = c.table_schema and t.table_name = c.table_name
   where c.table_schema = 'public'
   order by c.table_name, c.ordinal_position`);
const { rows: enums } = await client.query(`
  select t.typname as name, array_agg(e.enumlabel order by e.enumsortorder) as labels
    from pg_type t join pg_enum e on e.enumtypid = t.oid
    join pg_namespace n on n.oid = t.typnamespace
   where n.nspname = 'public' group by t.typname order by t.typname`);
await client.end();

const enumNames = new Set(enums.map((e) => e.name));
const tsType = (r) => {
  if (r.data_type === 'ARRAY') {
    const base = r.udt_name.replace(/^_/, '');
    const inner = enumNames.has(base) ? `Database['public']['Enums']['${base}']` : (TS[{ int4: 'integer', int8: 'bigint', float8: 'double precision', varchar: 'text' }[base] ?? base] ?? 'string');
    return `${inner}[]`;
  }
  if (r.data_type === 'USER-DEFINED' && enumNames.has(r.udt_name)) return `Database['public']['Enums']['${r.udt_name}']`;
  return TS[r.data_type] ?? 'unknown';
};

const tables = new Map();
for (const r of rows) {
  if (!tables.has(r.table_name)) tables.set(r.table_name, { view: r.table_type !== 'BASE TABLE', cols: [] });
  tables.get(r.table_name).cols.push(r);
}

const block = (name, t) => {
  const row = t.cols.map((c) => `          ${c.column_name}: ${tsType(c)}${c.is_nullable === 'YES' ? ' | null' : ''}`).join('\n');
  const ins = t.cols.map((c) => {
    const optional = c.is_nullable === 'YES' || c.column_default != null || c.is_identity === 'YES';
    return `          ${c.column_name}${optional ? '?' : ''}: ${tsType(c)}${c.is_nullable === 'YES' ? ' | null' : ''}`;
  }).join('\n');
  const upd = t.cols.map((c) => `          ${c.column_name}?: ${tsType(c)}${c.is_nullable === 'YES' ? ' | null' : ''}`).join('\n');
  return t.view
    ? `      ${name}: {\n        Row: {\n${row}\n        }\n      }`
    : `      ${name}: {\n        Row: {\n${row}\n        }\n        Insert: {\n${ins}\n        }\n        Update: {\n${upd}\n        }\n      }`;
};

const tablesTs = [...tables].filter(([, t]) => !t.view).map(([n, t]) => block(n, t)).join('\n');
const viewsTs = [...tables].filter(([, t]) => t.view).map(([n, t]) => block(n, t)).join('\n');
const enumsTs = enums.map((e) => `      ${e.name}: ${e.labels.map((l) => JSON.stringify(l)).join(' | ')}`).join('\n');

const src = `// AUTO-GENERATED by api/scripts/gen-types.mjs from our own Postgres (public schema).
// Do not edit by hand. Regenerate after adding a migration in api/migrations/.
export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];

export type Database = {
  public: {
    Tables: {
${tablesTs}
    }
    Views: {
${viewsTs}
    }
    Enums: {
${enumsTs}
    }
  }
};

type PublicSchema = Database['public'];
export type Tables<T extends keyof PublicSchema['Tables']> = PublicSchema['Tables'][T]['Row'];
export type TablesInsert<T extends keyof PublicSchema['Tables']> = PublicSchema['Tables'][T]['Insert'];
export type TablesUpdate<T extends keyof PublicSchema['Tables']> = PublicSchema['Tables'][T]['Update'];
export type Enums<T extends keyof PublicSchema['Enums']> = PublicSchema['Enums'][T];
`;
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, src);
console.log(`wrote ${out}: ${tables.size} tables/views, ${enums.length} enums`);
