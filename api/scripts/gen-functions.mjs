// Generates api/src/functions.generated.ts: one lazy loader per supabase/functions/<name>/index.ts
import { readdirSync, existsSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const dir = join(root, 'supabase', 'functions');
const names = readdirSync(dir).filter((n) => !n.startsWith('_') && existsSync(join(dir, n, 'index.ts'))).sort();
const body = names.map((n) => `  '${n}': () => import('@edge/${n}/index.ts'),`).join('\n');
writeFileSync(
  join(root, 'api', 'src', 'functions.generated.ts'),
  `// AUTO-GENERATED by api/scripts/gen-functions.mjs - do not edit.\n` +
    `// The original Supabase Edge Functions (Deno) are loaded unchanged; see api/src/functions.ts.\n` +
    `export const FUNCTION_LOADERS: Record<string, () => Promise<unknown>> = {\n${body}\n};\n`,
);
console.log(`functions: ${names.length}`);
